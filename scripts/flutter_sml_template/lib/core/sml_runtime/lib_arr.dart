/// `arr.*` (see supported.md's `arr` namespace, `lib_array`) - arrays: add,
/// remove, search, sort, count. Stateless/pure, generic over the list's own
/// element type so a `List<String>`/`List<int>`/`List<MyStruct>` all work
/// through the same functions without a cast.
///
/// Indices are 0-based throughout (ADR-004 in the SML spec) and match
/// Dart's own `List` indexing directly - no adjustment needed anywhere
/// here, which is exactly the point of that design decision.
class SmlArr {
  const SmlArr._();

  /// `ArrayAdd`/`ArrayAddLine` - returns the (0-based) index of the new
  /// element, mutating [list] in place.
  static int add<T>(List<T> list, T value) {
    list.add(value);
    return list.length - 1;
  }

  static void clear<T>(List<T> list) => list.clear();

  /// `ArrayCreation` -> `arr.create()` - an empty, growable list. `T` is
  /// inferred from the assignment context (`List<String> x = SmlArr.create();`
  /// infers `T=String` the same way Dart infers it for `<T>[]` directly) -
  /// never needs to be spelled out explicitly at the call site.
  static List<T> create<T>() => <T>[];

  static List<T> copy<T>(List<T> list) => List<T>.from(list);

  static int count<T>(List<T> list) => list.length;

  /// `ArraySeek` - returns -1 when nothing matches, same sentinel as
  /// WinDev's own (and Dart's `List.indexOf`), so no translation needed.
  static int find<T>(List<T> list, T value) => list.indexOf(value);

  /// `ArraySeek(array, asLinear, "FieldName", value)` - WinDev's search-by-
  /// named-field-of-a-struct-array form (confirmed real: searching an array
  /// of records for the row whose named field matches a value, e.g. finding
  /// a subscriber by `subscriber_no`). `selector` is generated by
  /// sml_to_dart.js from the SML call's literal field name at TRANSLATE
  /// time (`(item) => item.FieldName`) - Dart has no reflection to look up
  /// a field by a runtime string name, so this never needs any. The search
  /// mode argument itself (`asLinear`) carries no meaning here - a plain
  /// Dart `List` has no other way to search anyway.
  static int findByField<T, F>(List<T> list, F Function(T) selector, F value) {
    for (var i = 0; i < list.length; i++) {
      if (selector(list[i]) == value) return i;
    }
    return -1;
  }

  /// `ArrayInfo` - WinDev's own documentation of this call is thin and it
  /// never appears in real project code; best-effort element count until a
  /// real use case defines what more it should return.
  static int info<T>(List<T> list) => list.length;

  static void insert<T>(List<T> list, int index, T value) {
    final at = index.clamp(0, list.length);
    list.insert(at, value);
  }

  static String join<T>(List<T> list, String separator) => list.join(separator);

  static void removeAt<T>(List<T> list, int index) {
    if (index >= 0 && index < list.length) {
      list.removeAt(index);
    }
  }

  static void shuffle<T>(List<T> list) => list.shuffle();

  static void sort<T>(List<T> list, {bool descending = false}) {
    list.sort();
    if (descending) {
      final reversed = list.reversed.toList();
      list
        ..clear()
        ..addAll(reversed);
    }
  }
}
